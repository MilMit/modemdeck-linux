use super::Language;

/// Single-source-of-truth localization entry across all 8 supported languages.
pub struct LocaleEntry {
    pub key: &'static str,
    pub en: &'static str,
    pub fa: &'static str,
    pub ar: &'static str,
    pub tr: &'static str,
    pub de: &'static str,
    pub fr: &'static str,
    pub es: &'static str,
    pub ru: &'static str,
}

impl LocaleEntry {
    pub const fn get(&self, lang: Language) -> &'static str {
        match lang {
            Language::En => self.en,
            Language::Fa => self.fa,
            Language::Ar => self.ar,
            Language::Tr => self.tr,
            Language::De => self.de,
            Language::Fr => self.fr,
            Language::Es => self.es,
            Language::Ru => self.ru,
        }
    }
}

